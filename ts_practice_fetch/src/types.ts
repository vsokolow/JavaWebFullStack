/* ------------------------------------------------------------
   1. Категории

   В API их 24 штуки, но для занятия мы берём 5.
   Это union-тип: переменная типа Category может быть равна
   только одной из перечисленных строк — и ничему больше.

   Попробуйте на занятии написать:
       const c: Category = "shoes";
   и посмотрите, что скажет TypeScript.
------------------------------------------------------------ */
export type Category =
  | "smartphones"
  | "laptops"
  | "fragrances"
  | "groceries"
  | "furniture";

/* Тот же список, но как массив — чтобы построить <option> в select'е.
   `as const` заставляет TypeScript считать это массивом конкретных
   строк, а не просто string[]. Уберите as const и наведитесь на
   CATEGORIES — увидите разницу. */
export const CATEGORIES = [
  "smartphones",
  "laptops",
  "fragrances",
  "groceries",
  "furniture",
] as const;

/* В фильтре есть ещё вариант «все категории», которого нет в API.
   Поэтому тип фильтра — это Category плюс строка "all". */
export type CategoryFilter = Category | "all";

/* ------------------------------------------------------------
   2. Модель API

   Так выглядит товар в ответе dummyjson. Полей в реальном ответе
   больше двадцати, но мы описываем только те, что используем:
   TypeScript не требует описывать всё, лишние поля он просто
   не даст использовать по имени.
------------------------------------------------------------ */
export interface ApiProduct {
  id: number;
  title: string;
  description: string;
  price: number;
  rating: number;
  stock: number;
  category: string; // именно string: API не знает про наш union
  thumbnail: string;
}

/* Ответ приходит не массивом, а «конвертом»:
   { products: [...], total: 194, skip: 0, limit: 30 }

   Обратите внимание на <T> — это дженерик, шаблон.
   ApiListResponse<ApiProduct> означает «конверт с товарами внутри».
   Тот же конверт API использует и для пользователей, и для рецептов. */
export interface ApiListResponse<T> {
  products: T[];
  total: number;
  skip: number;
  limit: number;
}

/* ------------------------------------------------------------
   3. Наша внутренняя модель

   Зачем отдельный тип, если есть ApiProduct?

   Потому что модель API — чужая. Завтра dummyjson переименует
   thumbnail в image, и если ApiProduct растащен по всему коду,
   чинить придётся в двадцати местах. А так — только в одной
   функции toProduct().

   Отличия от ApiProduct:
   - image вместо thumbnail (имя понятнее);
   - inStock: boolean вместо stock: number (нам не важно сколько,
     важно есть или нет);
   - нет description и rating — в списке они не нужны.
------------------------------------------------------------ */
export interface Product {
  id: number;
  title: string;
  price: number;
  category: string;
  image: string;
  inStock: boolean;
}

